// Command generateclient wraps generated endpoint calls in the shared SDK policy.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"slices"
	"strconv"
	"strings"
)

type operation struct {
	ID         string              `json:"operationId"`
	Deprecated bool                `json:"deprecated"`
	Responses  map[string]response `json:"responses"`
}

type response struct {
	Ref     string `json:"$ref"`
	Content map[string]struct {
		Schema struct {
			Ref string `json:"$ref"`
		} `json:"schema"`
	} `json:"content"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	snapshot, err := os.ReadFile("api/openapi.json")
	if err != nil {
		return err
	}
	source, err := os.ReadFile("api/client.gen.go")
	if err != nil {
		return err
	}
	output, err := generate(snapshot, source)
	if err != nil {
		return err
	}
	return os.WriteFile("endpoints.gen.go", output, 0644)
}

func generate(snapshot, source []byte) ([]byte, error) {
	var spec struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Responses map[string]response `json:"responses"`
		} `json:"components"`
	}
	if err := json.Unmarshal(snapshot, &spec); err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "client.gen.go", source, 0)
	if err != nil {
		return nil, err
	}
	methods := map[string]*ast.FuncType{}
	ast.Inspect(file, func(node ast.Node) bool {
		decl, ok := node.(*ast.TypeSpec)
		if !ok || decl.Name.Name != "ClientInterface" {
			return true
		}
		if iface, ok := decl.Type.(*ast.InterfaceType); ok {
			for _, method := range iface.Methods.List {
				if signature, ok := method.Type.(*ast.FuncType); ok && len(method.Names) == 1 {
					methods[method.Names[0].Name] = signature
				}
			}
		}
		return false
	})
	var output bytes.Buffer
	output.WriteString("// Code generated by internal/cmd/generateclient. DO NOT EDIT.\n\npackage castle\n\nimport (\n\"context\"\n\"io\"\n\n\"github.com/fchimpan/castle-go/api\"\n)\n")
	paths := sortedKeys(spec.Paths)
	seen := map[string]bool{}
	for _, path := range paths {
		for _, verb := range []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"} {
			raw, exists := spec.Paths[path][verb]
			if !exists {
				continue
			}
			var op operation
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, err
			}
			if op.ID == "" || seen[op.ID] {
				return nil, fmt.Errorf("missing or duplicate operation ID for %s %s", verb, path)
			}
			seen[op.ID] = true
			name := strings.ToUpper(op.ID[:1]) + op.ID[1:]
			if methods[name] == nil {
				return nil, fmt.Errorf("no generated typed method for %s", op.ID)
			}
			policies, err := responsePolicies(op, spec.Components.Responses)
			if err != nil {
				return nil, err
			}
			for _, method := range []string{name, name + "WithBody"} {
				signature := methods[method]
				if signature == nil {
					continue
				}
				var params, args []string
				for _, field := range signature.Params.List {
					if len(field.Names) != 1 {
						return nil, fmt.Errorf("unsupported parameter shape for %s", method)
					}
					param := field.Names[0].Name
					if param == "reqEditors" {
						continue
					}
					typ, err := qualifiedType(field.Type)
					if err != nil {
						return nil, err
					}
					params = append(params, param+" "+typ)
					args = append(args, param)
				}
				fmt.Fprintf(&output, "\n// %s calls %s %s with the shared client policy.\n", method, strings.ToUpper(verb), path)
				if op.Deprecated {
					output.WriteString("// Deprecated: This operation is deprecated in Castle's API specification.\n")
				}
				fmt.Fprintf(&output, "func (c *Client) %s(%s) (*api.%sResponse, error) {\n", method, strings.Join(params, ", "), name)
				fmt.Fprintf(&output, "resp, err := c.api.%s(%s)\n", method, strings.Join(args, ", "))
				fmt.Fprintf(&output, "return finishResponse(resp, err, api.Parse%sResponse, c.maxResponseBytes, %s)\n}\n", name, strings.Join(policies, ", "))
			}
		}
	}
	if len(seen) == 0 {
		return nil, fmt.Errorf("specification has no operations")
	}
	return format.Source(output.Bytes())
}

func responsePolicies(op operation, components map[string]response) ([]string, error) {
	var policies []string
	for _, code := range sortedKeys(op.Responses) {
		status, err := strconv.Atoi(code)
		if err != nil {
			return nil, fmt.Errorf("unsupported response status %q in %s", code, op.ID)
		}
		if status < 200 || status >= 400 {
			continue
		}
		resp := op.Responses[code]
		seen := map[string]bool{}
		for resp.Ref != "" {
			ref := resp.Ref
			if seen[ref] || !strings.HasPrefix(ref, "#/components/responses/") {
				return nil, fmt.Errorf("unsupported response reference in %s: %s", op.ID, ref)
			}
			seen[ref] = true
			var ok bool
			resp, ok = components[strings.TrimPrefix(ref, "#/components/responses/")]
			if !ok {
				return nil, fmt.Errorf("missing response reference in %s: %s", op.ID, ref)
			}
		}
		var contentTypes []string
		assessment := false
		for _, contentType := range sortedKeys(resp.Content) {
			contentTypes = append(contentTypes, strconv.Quote(contentType))
			if resp.Content[contentType].Schema.Ref == "#/components/schemas/FilterAndRiskResponse" {
				assessment = true
			}
		}
		policy := fmt.Sprintf("responsePolicy{status: %d", status)
		if len(contentTypes) > 0 {
			policy += ", contentTypes: []string{" + strings.Join(contentTypes, ", ") + "}"
		}
		if assessment {
			policy += ", assessment: true"
		}
		policies = append(policies, policy+"}")
	}
	if len(policies) == 0 {
		return nil, fmt.Errorf("operation %s has no documented success response", op.ID)
	}
	return policies, nil
}

func qualifiedType(expr ast.Expr) (string, error) {
	switch expr := expr.(type) {
	case *ast.Ident:
		if types.Universe.Lookup(expr.Name) != nil {
			return expr.Name, nil
		}
		return "api." + expr.Name, nil
	case *ast.StarExpr:
		inner, err := qualifiedType(expr.X)
		return "*" + inner, err
	case *ast.SelectorExpr:
		var output bytes.Buffer
		err := format.Node(&output, token.NewFileSet(), expr)
		return output.String(), err
	default:
		return "", fmt.Errorf("unsupported generated parameter type %T", expr)
	}
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
